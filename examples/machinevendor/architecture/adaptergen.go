package architecture

import (
	"fmt"
	"go/format"
	"go/token"
	"strings"
)

// AdapterGo generates only the action surface and dispatch. It deliberately
// includes no guards, transitions, expected results or projection implementation.
func (m *Model) AdapterGo() ([]byte, error) {
	var b strings.Builder
	fmt.Fprintln(&b, "// Code generated by arch generate. DO NOT EDIT.\npackage generated\n\nimport \"fmt\"")
	fmt.Fprintf(&b, "const ModelSHA256 = %q\n", digest([]byte(m.Quint())))
	names := map[string]string{}
	used := map[string]bool{}
	fmt.Fprintln(&b, "type ActionDriver interface {")
	for _, a := range m.Actions {
		parts := strings.Split(a.ID, ".")
		var name string
		for _, part := range parts {
			if part == "" {
				return nil, fmt.Errorf("invalid action ID %q", a.ID)
			}
			name += strings.ToUpper(part[:1]) + part[1:]
		}
		if !token.IsIdentifier(name) || used[name] {
			return nil, fmt.Errorf("action %q has invalid or colliding Go method %q", a.ID, name)
		}
		used[name], names[a.ID] = true, name
		fmt.Fprintf(&b, "%s(", name)
		for i := range a.Params {
			if i > 0 {
				fmt.Fprint(&b, ", ")
			}
			fmt.Fprintf(&b, "p%d string", i)
		}
		fmt.Fprintln(&b, ") (bool, error)")
	}
	fmt.Fprintln(&b, "}\nfunc Dispatch(d ActionDriver, action string, args map[string]string) (bool, error) {\nswitch action {")
	for _, a := range m.Actions {
		fmt.Fprintf(&b, "case %q:\nif len(args) != %d { return false, fmt.Errorf(\"wrong argument count for %%s\", action) }\n", a.ID, len(a.Params))
		for _, p := range a.Params {
			fmt.Fprintf(&b, "if v, ok := args[%q]; !ok || v == \"\" { return false, fmt.Errorf(\"missing argument %%s for %%s\", %q, action) }\n", p, p)
		}
		fmt.Fprintf(&b, "return d.%s(", names[a.ID])
		for i, p := range a.Params {
			if i > 0 {
				fmt.Fprint(&b, ", ")
			}
			fmt.Fprintf(&b, "args[%q]", p)
		}
		fmt.Fprintln(&b, ")")
	}
	b.WriteString("default: return false, fmt.Errorf(\"unknown adapter action %s\", action)\n}\n}\n")
	return format.Source([]byte(b.String()))
}
