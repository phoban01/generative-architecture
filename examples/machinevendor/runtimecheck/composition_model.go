type Composition struct {
	Process      string `yaml:"process"`
	ResultPolicy string `yaml:"resultPolicy"`
}

func loadComposition(root string) (Composition, *behaviorgen.Program, Profile, error) {
	var cfg Composition
	profile, err := Load(root)
	if err != nil {
		return cfg, nil, profile, err
	}
	var sys architecture.System
	if _, err = krm.Read(filepath.Join(root, "system.yaml"), "System", &sys); err != nil {
		return cfg, nil, profile, err
	}
	if sys.Composition == "" {
		return cfg, nil, profile, fmt.Errorf("System.spec.composition is required")
	}
	path, err := sourcegen.LocalPath(root, sys.Composition)
	if err != nil {
		return cfg, nil, profile, err
	}
	if _, err = krm.Read(path, "ProcessComposition", &cfg); err != nil {
		return cfg, nil, profile, err
	}
	if cfg.ResultPolicy != "propagate-error" {
		return cfg, nil, profile, fmt.Errorf("unsupported process result policy")
	}
	p, err := behaviorgen.LoadProgram(root, cfg.Process)
	if err != nil {
		return cfg, nil, profile, err
	}
	selected := p.Selection()
	if selected.Component != "mac" || selected.Action != "publish" || selected.Receiver != "MACReconciler" || selected.Method != "Publish" || selected.AllowStalePublication {
		return cfg, nil, profile, fmt.Errorf("no paused adapter for selected process")
	}
	return cfg, p, profile, nil
}

var compositionVariables = map[string]string{
	"s":     `{ ready: bool, processing: bool, dirty: bool, due: int, now: int, retries: int, lease: bool, cached: bool, observed: bool, published: bool, accepted: bool, fresh: bool }`,
	"event": "str", "tick": "int", "stage": "int", "pc": "int", "observed": "Assignment", "claim": "Assignment", "err": "bool", "returnedError": "bool", "injected": "bool",
	"localMachineId": "str", "publishedMachineId": "str", "cachedMachineId": "str", "apiRevision": "int", "cacheRevision": "int", "readRevision": "int",
}

func composedTransition(guard string, updates map[string]string) string {
	names := make([]string, 0, len(compositionVariables))
	for k := range compositionVariables {
		names = append(names, k)
	}
	sort.Strings(names)
	parts := []string{guard}
	for _, k := range names {
		v, ok := updates[k]
		if !ok {
			v = k
		}
		parts = append(parts, k+"' = "+v)
	}
	return "all {\n  " + strings.Join(parts, ",\n  ") + "\n }"
}
func composedModel(p *behaviorgen.Program, profile Profile) (string, error) {
	var b strings.Builder
	b.WriteString(`// GENERATED by composing Go-extracted process nodes with the shared queue model.
// Pure Go steps stutter in replay; client boundaries and method returns are observed.
module Composed {
 type Assignment = { machineId: str, epoch: int }
 pure val EMPTY = { machineId: "", epoch: 0 }
 pure val ORIGINAL = { machineId: "host-1", epoch: 1 }
 pure val REVOKED = { machineId: "", epoch: 1 }
`)
	names := make([]string, 0, len(compositionVariables))
	for k := range compositionVariables {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		fmt.Fprintf(&b, " var %s: %s\n", k, compositionVariables[k])
	}
	b.WriteString(" val lease = if (s.lease) ORIGINAL else REVOKED\n")
	b.WriteString(queueHelpers(profile))
	emit := func(name, guard, event string, updates map[string]string) {
		if updates == nil {
			updates = map[string]string{}
		}
		updates["event"] = strconv.Quote(event)
		updates["tick"] = "tick+1"
		updates["injected"] = "false"
		fmt.Fprintf(&b, " action %s = %s\n", name, composedTransition(guard, updates))
	}
	init := map[string]string{"s": `{ready:false,processing:false,dirty:false,due:-1,now:0,retries:0,lease:true,cached:true,observed:false,published:false,accepted:false,fresh:true}`, "event": `"init"`, "tick": "0", "stage": "0", "pc": "-1", "observed": "EMPTY", "claim": "EMPTY", "err": "false", "returnedError": "false", "injected": "false", "localMachineId": `""`, "publishedMachineId": `""`, "cachedMachineId": `""`, "apiRevision": "0", "cacheRevision": "0", "readRevision": "-1"}
	fmt.Fprintf(&b, " action init = %s\n", composedTransition("true", init))
	emit("enqueue", "true", "enqueue", map[string]string{"s": "queueEnqueue(s)"})
	emit("start", "s.ready and not(s.processing) and stage == 0", "start", map[string]string{"s": `queueStart(s).with("observed",false).with("accepted",false)`, "stage": "1", "observed": "EMPTY", "claim": "EMPTY", "localMachineId": `""`, "readRevision": "-1", "err": "false", "returnedError": "false"})
	emit("observe", "s.processing and stage == 1", "observe", map[string]string{"s": `s.with("observed",s.cached)`, "observed": "if (s.cached) ORIGINAL else REVOKED", "stage": "2"})
	emit("begin", "s.processing and stage == 2", "begin", map[string]string{"stage": "3", "pc": strconv.Itoa(p.Entry)})
	emit("finish", "s.processing and stage == 4", "finish", map[string]string{"s": `queueComplete(s, if (returnedError) "error" else "success")`, "stage": "0"})
	emit("revoke", "true", "revoke", map[string]string{"s": `s.with("lease",false)`})
	emit("syncCache", "true", "cache-sync", map[string]string{"s": `s.with("cached",s.lease)`})
	emit("syncInfraCache", "true", "infra-cache-sync", map[string]string{"s": `s.with("fresh",true)`, "cacheRevision": "apiRevision", "cachedMachineId": "publishedMachineId"})
	emit("externalWrite", "true", "infra-change", map[string]string{"s": `s.with("published",false).with("fresh",false)`, "apiRevision": "apiRevision+1", "publishedMachineId": `""`})
	emit("timePasses", fmt.Sprintf("s.now < %d", profile.MaxTicks), "time", map[string]string{"s": `s.with("now",s.now+1)`})
	emit("fire", "s.due >= 0 and s.now >= s.due", "fire", map[string]string{"s": "queueFire(s)"})
	emit("idle", "true", "idle", nil)
	var nodes []string
	kinds := map[string]int{}
	for _, n := range p.Nodes {
		updates := map[string]string{"pc": strconv.Itoa(n.Next), "event": strconv.Quote(n.Kind), "tick": "tick+1", "injected": "false"}
		call := fmt.Sprintf("node%d(false)", n.ID)
		switch n.Kind {
		case "branch":
			updates["pc"] = fmt.Sprintf("if (%s) %d else %d", n.Expression, n.Next, n.Else)
		case "readClaim":
			updates["claim"] = "if (failed) claim else lease"
			updates["err"] = "failed"
			updates["injected"] = "failed"
			call = fmt.Sprintf("node%d(failed)", n.ID)
		case "readInfra":
			updates["localMachineId"] = "if (failed) localMachineId else cachedMachineId"
			updates["readRevision"] = "if (failed) readRevision else cacheRevision"
			updates["err"] = "failed"
			updates["injected"] = "failed"
			call = fmt.Sprintf("node%d(failed)", n.ID)
		case "setField":
			updates["localMachineId"] = n.Expression
			updates["err"] = "false"
		case "updateStatus":
			failed := "(failed or readRevision != apiRevision)"
			updates["err"] = failed
			updates["injected"] = "failed"
			updates["event"] = `if (` + failed + `) "writeError" else "commit"`
			updates["publishedMachineId"] = "if (" + failed + ") publishedMachineId else localMachineId"
			updates["apiRevision"] = "if (" + failed + ") apiRevision else apiRevision+1"
			updates["s"] = `if (` + failed + `) s else s.with("published",localMachineId != "").with("fresh",false)`
			call = fmt.Sprintf("node%d(failed)", n.ID)
		case "return":
			if n.ReturnError != "err" && n.ReturnError != "false" {
				return "", fmt.Errorf("unsupported return error summary")
			}
			updates["s"] = `s.with("accepted",` + n.Expression + `)`
			updates["returnedError"] = n.ReturnError
			updates["stage"] = "4"
		default:
			return "", fmt.Errorf("unsupported process node %q", n.Kind)
		}
		if n.Kind == "readClaim" || n.Kind == "readInfra" || n.Kind == "updateStatus" {
			if _, ok := kinds[n.Kind]; ok {
				return "", fmt.Errorf("adapter requires one %s boundary", n.Kind)
			}
			kinds[n.Kind] = n.ID
		}
		fmt.Fprintf(&b, " // %s:%d: %s\n action node%d(failed) = %s\n", p.Selection().Source, n.Line, strings.ReplaceAll(n.Source, "\n", " "), n.ID, composedTransition(fmt.Sprintf("s.processing and stage == 3 and pc == %d", n.ID), updates))
		nodes = append(nodes, call)
	}
	for _, k := range []string{"readClaim", "readInfra", "updateStatus"} {
		if _, ok := kinds[k]; !ok {
			return "", fmt.Errorf("missing %s boundary", k)
		}
	}
	fmt.Fprintf(&b, " action program(failed) = any { %s }\n", strings.Join(nodes, ", "))
	b.WriteString(` action step = any {enqueue,start,observe,begin,program(false),program(true),finish,revoke,syncCache,syncInfraCache,externalWrite,timePasses,fire,idle}
 action driveOnce = if (tick == 0) enqueue else if (s.ready and stage == 0) start else if (stage == 1) observe else if (stage == 2) begin else if (stage == 3) program(false) else if (stage == 4) finish else idle
 action successStep = driveOnce
 action staleStep = if (tick == 4) revoke else driveOnce
 action raceStep = if (event == "readClaim") revoke else if (event == "revoke") syncCache else driveOnce
 action conflictStep = if (event == "readInfra") externalWrite else driveOnce
 action dirtyStep = if (event == "readClaim") enqueue else driveOnce
 action conflictRetryStep =
  if (event == "readInfra" and s.retries == 0) externalWrite
  else if (stage == 0 and s.due >= 0) {
   if (cacheRevision != apiRevision) syncInfraCache else if (s.now < s.due) timePasses else fire
  } else driveOnce
`)
	for _, name := range []string{"readClaim", "readInfra", "updateStatus"} {
		fmt.Fprintf(&b, " action %sErrorStep = if (stage == 3 and pc == %d) program(true) else driveOnce\n", name, kinds[name])
	}
	requirements, err := p.QuintRequirements()
	if err != nil {
		return "", err
	}
	b.WriteString(requirements)
	b.WriteString(` val queueSafety = not(s.ready and s.processing) and (not(s.ready) or s.dirty)
 val composedSafety = queueSafety and publicationUsesCheckedLease
}
`)
	return b.String(), nil
}
func GenerateComposition(root string) (string, error) {
	if _, err := Generate(root); err != nil {
		return "", err
	}
	if err := architecture.ExtractSources(root); err != nil {
		return "", err
	}
	cfg, p, profile, err := loadComposition(root)
	if err != nil {
		return "", err
	}
	model, err := composedModel(p, profile)
	if err != nil {
		return "", err
	}
	dir := filepath.Join(root, "generated/composition")
	if err = os.MkdirAll(dir, 0755); err != nil {
		return "", err
	}
	if err = os.WriteFile(filepath.Join(dir, "Composed.qnt"), []byte(model), 0644); err != nil {
		return "", err
	}
	err = krm.WriteResult(filepath.Join(dir, "composition.yaml"), "ComposedProgram", "mac-publication-runtime", map[string]any{"processAnalysis": cfg.Process, "resultPolicy": cfg.ResultPolicy, "profile": profile, "program": p, "replay": "unmodified Go method paused at client boundaries; pure control flow is stuttering"})
	return model, err
}
