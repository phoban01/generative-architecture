// Package adaptergen generates replay adapter code from the IR and the
// abstraction document: projections that read implementation state through
// API clients, environment actions that drive the API between steps, and
// boundary gating for process nodes, gating proxies for Go interfaces whose
// methods are effects, reference checks, and the routing of runtime events
// to a controller-runtime worker. Generated code takes only API clients, gates
// and workers as inputs; it never consults expected model state (ADR-0005).
//
// Every generator returns formatted Go source for a self-contained file.
// Helpers in each file carry a distinct prefix so the files of one package
// can be emitted side by side.
package adaptergen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"strconv"
	"strings"
	"text/template"

	"generative-architecture/pkg/ir"
)

// Header is the first line of every generated file.
const Header = "// Code generated by adaptergen. DO NOT EDIT."

var funcs = template.FuncMap{
	"q":    strconv.Quote,
	"gvk":  gvkLiteral,
	"path": pathLiteral,
}

// gvkLiteral renders an apimachinery GroupVersionKind composite literal.
func gvkLiteral(g ir.GVK) string {
	return fmt.Sprintf("schema.GroupVersionKind{Group: %s, Version: %s, Kind: %s}", strconv.Quote(g.Group), strconv.Quote(g.Version), strconv.Quote(g.Kind))
}

// pathLiteral renders path elements as a quoted argument list.
func pathLiteral(path []string) string {
	parts := make([]string, len(path))
	for i, p := range path {
		parts[i] = strconv.Quote(p)
	}
	return strings.Join(parts, ", ")
}

// validPackage accepts a Go package identifier.
func validPackage(pkg string) error {
	if !token.IsIdentifier(pkg) || pkg == "_" {
		return fmt.Errorf("package name %q is not a Go identifier", pkg)
	}
	return nil
}

// render executes a template and formats the result with go/format, so
// malformed output is rejected at generation time.
func render(name, text string, data any) ([]byte, error) {
	t, err := template.New(name).Funcs(funcs).Parse(text)
	if err != nil {
		return nil, fmt.Errorf("%s template: %w", name, err)
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("%s template: %w", name, err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated %s does not parse: %w", name, err)
	}
	return src, nil
}

// objectKey resolves the object a generator addresses: the key's GVK when
// set must agree with the resource, a name is required and a cluster other
// than the implicit one is not supported by a single dynamic client.
func objectKey(resource ir.GVK, key ir.ObjectRef) (ir.ObjectRef, error) {
	if err := resource.Validate(); err != nil {
		return key, err
	}
	if key.GVK == (ir.GVK{}) {
		key.GVK = resource
	} else if key.GVK != resource {
		return key, fmt.Errorf("object %s does not belong to resource %s", key, resource)
	}
	if key.Name == "" {
		return key, fmt.Errorf("object of %s has no name", resource)
	}
	if key.Cluster != "" {
		return key, fmt.Errorf("object %s: one dynamic client serves one cluster; cluster %q is not supported", key, key.Cluster)
	}
	return key, nil
}

// splitPath splits a dot-joined JSON path into identifier elements.
func splitPath(key string) ([]string, error) {
	if key == "" {
		return nil, fmt.Errorf("empty field path")
	}
	path := strings.Split(key, ".")
	for _, p := range path {
		if p == "" {
			return nil, fmt.Errorf("field path %q has an empty element", key)
		}
	}
	return path, nil
}
